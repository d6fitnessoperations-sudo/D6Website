#!/usr/bin/env python3
"""
D6 Fitness Studio - content updater

Run this after you add photos to a gallery folder or edit content/testimonials.json:

    python3 update_content.py

It does two things:
  1. Scans every sub-folder of assets/gallery/ and lists its images, so the
     gallery slideshows pick them up automatically.
  2. Reads content/testimonials.json and turns it into the testimonials shown on the site.
  3. Reads content/certifications.json, checks each certificate image exists, and
     prepares the certificate slider.
  4. Reads content/assessment.json (the Health & Fitness Assessment questions, scoring
     and suggestions), checks it, and prepares it for the website.

The results are written to small .js files that the page loads, so the site
still works when index.html is opened directly from your computer.
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GALLERY_DIR = os.path.join(HERE, "assets", "gallery")
GALLERY_OUT = os.path.join(GALLERY_DIR, "gallery-manifest.js")
TESTI_JSON = os.path.join(HERE, "content", "testimonials.json")
TESTI_OUT = os.path.join(HERE, "content", "testimonials.js")
CERT_JSON = os.path.join(HERE, "content", "certifications.json")
CERT_OUT = os.path.join(HERE, "content", "certifications.js")
ASSESS_JSON = os.path.join(HERE, "content", "assessment.json")
ASSESS_OUT = os.path.join(HERE, "content", "assessment.js")

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp", ".gif"}


def natural_key(text):
    return [int(part) if part.isdigit() else part.lower() for part in re.split(r"(\d+)", text)]


def build_gallery():
    manifest = {}
    if os.path.isdir(GALLERY_DIR):
        for folder in sorted(os.listdir(GALLERY_DIR)):
            folder_path = os.path.join(GALLERY_DIR, folder)
            if not os.path.isdir(folder_path):
                continue
            files = [f for f in os.listdir(folder_path)
                     if os.path.splitext(f)[1].lower() in IMAGE_EXTS]
            files.sort(key=natural_key)
            manifest[folder] = ["assets/gallery/%s/%s" % (folder, f) for f in files]

    with open(GALLERY_OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by update_content.py - do not edit by hand.\n")
        fh.write("window.D6_GALLERY = " + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n")

    for folder, files in manifest.items():
        print("  gallery/%-22s %d photo(s)" % (folder, len(files)))
    return manifest


def initials_for(name):
    words = [w for w in re.split(r"[\s.]+", name) if w]
    letters = "".join(w[0] for w in words[:2]).upper()
    return letters or "?"


def build_testimonials():
    if not os.path.isfile(TESTI_JSON):
        raise SystemExit("ERROR: %s not found" % TESTI_JSON)

    with open(TESTI_JSON, encoding="utf-8") as fh:
        try:
            data = json.load(fh)
        except json.JSONDecodeError as err:
            raise SystemExit("ERROR: testimonials.json is not valid JSON: %s" % err)

    items = data.get("testimonials") if isinstance(data, dict) else None
    if not isinstance(items, list):
        raise SystemExit('ERROR: testimonials.json must contain a "testimonials" list')

    cleaned = []
    for number, item in enumerate(items, 1):
        name = str(item.get("name", "")).strip()
        if not name:
            raise SystemExit("ERROR: testimonial #%d has no \"name\"" % number)

        paragraphs = item.get("paragraphs", [])
        if isinstance(paragraphs, str):
            paragraphs = [paragraphs]
        paragraphs = [str(p).strip() for p in paragraphs if str(p).strip()]
        if not paragraphs:
            raise SystemExit("ERROR: testimonial #%d (%s) has no \"paragraphs\"" % (number, name))

        entry = {
            "name": name,
            "role": str(item.get("role", "")).strip(),
            "initials": str(item.get("initials", "")).strip() or initials_for(name),
            "paragraphs": paragraphs,
        }
        if str(item.get("result", "")).strip():
            entry["result"] = str(item["result"]).strip()
        if str(item.get("title", "")).strip():
            entry["title"] = str(item["title"]).strip()
        cleaned.append(entry)

    with open(TESTI_OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by update_content.py from content/testimonials.json - do not edit by hand.\n")
        fh.write("window.D6_TESTIMONIALS = " + json.dumps(cleaned, ensure_ascii=False, indent=2) + ";\n")

    print("  testimonials: %d" % len(cleaned))
    return cleaned


def build_certifications():
    if not os.path.isfile(CERT_JSON):
        print("  certifications: no content/certifications.json (skipped)")
        return []
    with open(CERT_JSON, encoding="utf-8") as fh:
        try:
            data = json.load(fh)
        except json.JSONDecodeError as err:
            raise SystemExit("ERROR: certifications.json is not valid JSON: %s" % err)

    items = data.get("certifications") if isinstance(data, dict) else None
    if not isinstance(items, list):
        raise SystemExit('ERROR: certifications.json must contain a "certifications" list')

    cleaned = []
    for number, item in enumerate(items, 1):
        file_path = str(item.get("file", "")).strip()
        title = str(item.get("title", "")).strip()
        if not file_path or not title:
            raise SystemExit("ERROR: certification #%d needs \"file\" and \"title\"" % number)
        if not os.path.isfile(os.path.join(HERE, *file_path.split("/"))):
            raise SystemExit("ERROR: certification #%d file not found: %s" % (number, file_path))
        entry = {"file": file_path, "title": title}
        if str(item.get("issuer", "")).strip():
            entry["issuer"] = str(item["issuer"]).strip()
        cleaned.append(entry)

    with open(CERT_OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by update_content.py from content/certifications.json - do not edit by hand.\n")
        fh.write("window.D6_CERTIFICATIONS = " + json.dumps(cleaned, ensure_ascii=False, indent=2) + ";\n")

    print("  certifications: %d" % len(cleaned))
    return cleaned


def build_assessment():
    if not os.path.isfile(ASSESS_JSON):
        print("  assessment: no content/assessment.json (skipped)")
        return None
    with open(ASSESS_JSON, encoding="utf-8") as fh:
        try:
            data = json.load(fh)
        except json.JSONDecodeError as err:
            raise SystemExit("ERROR: assessment.json is not valid JSON: %s" % err)

    a = data.get("assessment") if isinstance(data, dict) else None
    if not isinstance(a, dict):
        raise SystemExit('ERROR: assessment.json must contain an "assessment" object')

    def fail(msg):
        raise SystemExit("ERROR: assessment.json - " + msg)

    for key in ("id", "version"):
        if not str(a.get(key, "")).strip():
            fail('"%s" is missing' % key)

    # Score bands must cover 0-100 with no gaps.
    bands = sorted(a.get("bands", []), key=lambda b: b["min"])
    band_ids = [b["id"] for b in bands]
    if not bands or bands[0]["min"] != 0 or bands[-1]["max"] != 100:
        fail('"bands" must cover 0 to 100')
    for prev, nxt in zip(bands, bands[1:]):
        if nxt["min"] != prev["max"] + 1:
            fail('"bands" has a gap or overlap near %s' % nxt["id"])

    # Stages must cover 0-100 with no gaps.
    stages = sorted(a.get("stages", []), key=lambda s: s["min"])
    if not stages or stages[0]["min"] != 0 or stages[-1]["max"] != 100:
        fail('"stages" must cover 0 to 100')
    for prev, nxt in zip(stages, stages[1:]):
        if nxt["min"] != prev["max"] + 1:
            fail('"stages" has a gap or overlap near "%s"' % nxt.get("label"))

    categories = a.get("categories", [])
    if not categories:
        fail('"categories" is empty')
    cat_ids = set()
    total_weight = 0
    for cat in categories:
        cid = str(cat.get("id", "")).strip()
        if not cid or not str(cat.get("name", "")).strip():
            fail('every category needs "id" and "name"')
        cat_ids.add(cid)
        total_weight += cat.get("weight", 0)
        suggestions = cat.get("suggestions", {})
        for bid in band_ids:
            if not str(suggestions.get(bid, "")).strip():
                fail('category "%s" has no suggestion for band "%s"' % (cid, bid))
    if total_weight != 100:
        fail('category weights must add up to 100 (currently %s)' % total_weight)

    questions = a.get("questions", [])
    if not questions:
        fail('"questions" is empty')
    seen = set()
    counts = {cid: 0 for cid in cat_ids}
    for q in questions:
        qid = str(q.get("id", "")).strip()
        if not qid or qid in seen:
            fail('question id missing or repeated: "%s"' % qid)
        seen.add(qid)
        if q.get("category") not in cat_ids:
            fail('question %s uses an unknown category "%s"' % (qid, q.get("category")))
        if q.get("type") not in ("single", "multiple", "yesno"):
            fail('question %s has an unknown type "%s"' % (qid, q.get("type")))
        if not str(q.get("text", "")).strip():
            fail("question %s has no text" % qid)
        opts = q.get("options", [])
        if len(opts) < 2:
            fail("question %s needs at least two options" % qid)
        for o in opts:
            if not str(o.get("label", "")).strip() or not isinstance(o.get("score"), (int, float)):
                fail("question %s has an option without a label or numeric score" % qid)
        counts[q["category"]] += 1

    for cid, n in counts.items():
        if n == 0:
            fail('category "%s" has no questions' % cid)

    with open(ASSESS_OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by update_content.py from content/assessment.json - do not edit by hand.\n")
        fh.write("window.D6_ASSESSMENT = " + json.dumps({"assessment": a}, ensure_ascii=False, indent=2) + ";\n")

    print("  assessment: %s v%s, %d questions, %d categories" % (a.get("name", a["id"]), a["version"], len(questions), len(categories)))
    return a


def main():
    print("Gallery folders:")
    build_gallery()
    print("Testimonials:")
    build_testimonials()
    print("Certifications:")
    build_certifications()
    print("Health & Fitness Assessment:")
    build_assessment()
    print("Done. Refresh index.html in your browser.")


if __name__ == "__main__":
    try:
        main()
    except SystemExit as exc:
        if exc.code not in (0, None):
            print(exc.code, file=sys.stderr)
        sys.exit(1 if exc.code not in (0, None) else 0)
